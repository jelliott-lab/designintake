// Builds the Google Apps Script version of the app into apps-script/:
//  - Index.html: public/index.html with the CSS and JS inlined (Apps Script serves one file)
//  - Code.gs:    DEFAULT_PRICING refreshed from config/pricing.default.json
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const out = path.join(root, 'apps-script');

const inlineScript = (file) => `<script>\n${read(file).replace(/<\/script/gi, '<\\/script')}\n</script>`;

let html = read('public/index.html');
html = html.replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${read('public/styles.css')}\n</style>`);
html = html.replace('<script src="logic.js"></script>', () => inlineScript('public/logic.js'));
html = html.replace('<script src="app.js"></script>', () => inlineScript('public/app.js'));
if (/(href|src)="(styles\.css|logic\.js|app\.js)"/.test(html)) throw new Error('Failed to inline an asset');
html = `<!-- GENERATED by scripts/build-apps-script.js from /public. Do not edit by hand. -->\n${html}`;
fs.writeFileSync(path.join(out, 'Index.html'), html);

const pricing = JSON.stringify(JSON.parse(read('config/pricing.default.json')), null, 2);
const codePath = path.join(out, 'Code.gs');
const code = fs.readFileSync(codePath, 'utf8').replace(
  /(\/\/ @@DEFAULT_PRICING_START\n)[\s\S]*?(\n\/\/ @@DEFAULT_PRICING_END)/,
  (_, start, end) => `${start}var DEFAULT_PRICING = ${pricing};${end}`,
);
if (!code.includes('var DEFAULT_PRICING = {\n')) throw new Error('DEFAULT_PRICING markers not found in Code.gs');
fs.writeFileSync(codePath, code);

console.log('Built apps-script/Index.html and apps-script/Code.gs');
