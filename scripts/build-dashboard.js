// Builds the marketing dashboard's Apps Script page: dashboard/apps-script/Index.html is
// dashboard/public/index.html with the CSS and JS inlined (Apps Script serves one file).
// sample-data.js is left out: the hosted dashboard always uses live data.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'dashboard');
const read = (p) => fs.readFileSync(path.join(dir, 'public', p), 'utf8');
const inlineScript = (file) => `<script>\n${read(file).replace(/<\/script/gi, '<\\/script')}\n</script>`;

let html = read('index.html');
html = html.replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${read('styles.css')}\n</style>`);
html = html.replace(/\n\s*<script src="sample-data\.js"><\/script>/, '');
for (const f of ['metrics.js', 'flags.js', 'charts.js', 'app.js']) {
  html = html.replace(`<script src="${f}"></script>`, () => inlineScript(f));
}
if (/(href|src)="[\w-]+\.(css|js)"/.test(html)) throw new Error('Failed to inline an asset');
html = `<!-- GENERATED by scripts/build-dashboard.js from dashboard/public. Do not edit by hand. -->\n${html}`;
fs.writeFileSync(path.join(dir, 'apps-script', 'Index.html'), html);
console.log('Built dashboard/apps-script/Index.html');
